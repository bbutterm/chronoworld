import { buildUnit, enemySquad, simulateBattle } from '../src/core';
import { loadFullContext } from './lib/content-node';
import { cardHero } from '../tests/helpers';
const ctx = loadFullContext();
const tier1 = ['alan', 'dorn', 'bran', 'kai', 'vika'];
const sq = tier1.map((t, i) => buildUnit(cardHero(ctx, t, 1, { id: `h${i}` }), ctx));
const r = simulateBattle(ctx.content, sq, enemySquad(process.argv[2] ?? 'ch1_s10', ctx), Number(process.argv[3] ?? 2027808044), { combat: ctx.combat });
const lo = Number(process.argv[4] ?? 3.5);
const hi = Number(process.argv[5] ?? 4.8);
for (const e of r.log) if (e.t >= lo && e.t <= hi && ['move', 'attack', 'death', 'turn'].includes(e.type)) console.log(JSON.stringify(e));
