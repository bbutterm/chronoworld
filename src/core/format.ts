/**
 * Число с разбивкой по разрядам для текста игроку: 20000 → «20 000». Разделитель — неразрывный пробел (U+00A0):
 * перенос строки внутри числа («3⏎200», LT-13) невозможен. Используют и тексты ошибок ядра, и экраны (formatNumber).
 */
export function groupDigits(n: number): string {
  return String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}
