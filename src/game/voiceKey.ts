/**
 * Ключ клипа озвучки (без Phaser — общий для игры и scripts/voice-gen.ts): хэш русской строки, как она выводится
 * на экран. Игра ищет клип по тексту реплики/страницы — отдельная разметка сюжета не нужна; правка текста = новый
 * ключ (старый клип просто перестаёт звучать, пока его не перегенерируют).
 */

/** Пробелы по краям и подряд не влияют на ключ. */
export const voiceText = (s: string): string => s.trim().replace(/\s+/g, ' ');

/** cyrb53 — 53-битный хэш строки, 14 шестнадцатеричных знаков (коллизии на десятках тысяч реплик не грозят). */
export function voiceKey(s: string): string {
  const str = voiceText(s);
  // Затравки cyrb53 (0xdeadbeef, 0x41c6ce57) — десятичными: линт интерфейса считает 0x… цветом.
  let h1 = 3735928559;
  let h2 = 1103547991;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16).padStart(14, '0');
}
