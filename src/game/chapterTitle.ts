/**
 * Название главы без префикса «Глава N.» (аудит 11.10, ui-core 3): на ленте Кампании номер уже стоит строкой ниже
 * («Глава 6 · 0 / 18»), а длинное имя («Глава 6. Затонувший корабль») обрезалось многоточием. data/campaign name
 * не меняем: сюжетные сцены и сводки показывают его целиком.
 */
export function chapterTitle(name: string): string {
  return name.replace(/^Глава\s*\d+\.\s*/, '');
}
